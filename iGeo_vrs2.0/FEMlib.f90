                        der(1,2)=(t3*t4+t1*t4+t1*t3)*d27/d16
                        der(1,3)=-(t2*t4+t1*t4+t1*t2)*d27/d16
                        der(1,4)=(t2*t3+t1*t3+t1*t2)*d9/d16
                    CASE(5)
                        t1=-one-xi
                        t2=-pt5-xi
                        t3=-xi
