        ndim=UBOUND(der,1)
        nod= UBOUND(der,2)
        SELECT CASE(ndim)
            CASE(1)   ! one dimensional elements
                xi=points(i,1)
                SELECT CASE(nod)
                    CASE(2)
                        der(1,1)=-pt5
                        der(1,2)= pt5
                    CASE(3)
                        t1=-one-xi
                        t2=-xi
                        t3=one-xi
                        der(1,1)=-(t3+t2)/two
                        der(1,2)=(t3+t1)
                        der(1,3)=-(t2+t1)/two
