                    CASE DEFAULT
                        WRITE(*,*)"wrong number of nodes in shape_functionDerivative"
                END SELECT
            CASE(2)      ! two dimensional elements
                xi=points(i,1)
                eta=points(i,2)
                c1=xi
                c2=eta
                c3=one-c1-c2
                etam=pt25*(one-eta)
                etap=pt25*(one+eta)
                xim= pt25*(one-xi)
                xip= pt25*(one+xi)
                x2p1=two*xi+one
                x2m1=two*xi-one
                e2p1=two*eta+one
                e2m1=two*eta-one
                SELECT CASE(nod)
